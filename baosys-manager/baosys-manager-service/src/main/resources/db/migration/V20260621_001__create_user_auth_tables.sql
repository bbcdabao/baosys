CREATE TABLE user_info (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name VARCHAR(128) NOT NULL,
    system_type VARCHAR(32) NOT NULL,
    user_pass VARCHAR(512) NOT NULL,
    user_permissions VARCHAR(1024) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by VARCHAR(128) NOT NULL,
    updated_by VARCHAR(128) NOT NULL,
    CONSTRAINT ck_user_info_system_type
        CHECK (system_type IN ('MANAGER', 'SIMULATION', 'SIMULATORS')),
    CONSTRAINT uk_user_info_user_name_system_type UNIQUE (user_name, system_type)
);

CREATE TABLE user_login (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_info_id BIGINT NOT NULL,
    login_client VARCHAR(512) NOT NULL,
    refresh_token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by VARCHAR(128) NOT NULL,
    updated_by VARCHAR(128) NOT NULL,
    CONSTRAINT uk_user_login_refresh_token_hash UNIQUE (refresh_token_hash),
    CONSTRAINT fk_user_login_user_info
        FOREIGN KEY (user_info_id)
        REFERENCES user_info (id)
        ON DELETE CASCADE
);

CREATE INDEX idx_user_login_user_info_id ON user_login (user_info_id);
CREATE INDEX idx_user_login_expires_at ON user_login (expires_at);

COMMENT ON TABLE user_info IS '系统账户信息';
COMMENT ON COLUMN user_info.system_type IS '所属系统类型：MANAGER=后台管理、SIMULATION=仿真平台、SIMULATORS=试验场平台';
COMMENT ON COLUMN user_info.user_pass IS 'BCrypt 密码摘要';
COMMENT ON COLUMN user_info.user_permissions IS '英文逗号分隔的权限编码';
COMMENT ON TABLE user_login IS '账户登录客户端与刷新令牌状态';
COMMENT ON COLUMN user_login.refresh_token_hash IS '刷新令牌 SHA-256 摘要';

CREATE OR REPLACE FUNCTION cleanup_inactive_user_login_sessions()
RETURNS integer
LANGUAGE plpgsql
AS $$
DECLARE
    deleted_count integer;
BEGIN
    DELETE FROM user_login
     WHERE updated_at < CURRENT_TIMESTAMP - INTERVAL '1 day';

    GET DIAGNOSTICS deleted_count = ROW_COUNT;
    RETURN deleted_count;
END;
$$;

COMMENT ON FUNCTION cleanup_inactive_user_login_sessions()
    IS 'Delete user_login rows whose updated_at has not changed for more than one day.';

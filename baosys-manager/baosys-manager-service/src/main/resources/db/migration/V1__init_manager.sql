-- Fresh database initialization: current Manager schema.
-- Single initial version; includes accounts, audit, OAuth2 and Spring Session.
CREATE TABLE user_info (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name VARCHAR(128) NOT NULL,
    user_pass VARCHAR(512) NOT NULL,
    user_permissions TEXT NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by VARCHAR(128) NOT NULL,
    updated_by VARCHAR(128) NOT NULL,
    CONSTRAINT uk_user_info_user_name UNIQUE (user_name)
);

-- Spring Authorization Server 1.5 JDBC schema, PostgreSQL text/timestamptz variants.
CREATE TABLE oauth2_authorization (
    id varchar(100) NOT NULL,
    registered_client_id varchar(100) NOT NULL,
    principal_name varchar(200) NOT NULL,
    authorization_grant_type varchar(100) NOT NULL,
    authorized_scopes varchar(1000) DEFAULT NULL,
    attributes text DEFAULT NULL,
    state varchar(500) DEFAULT NULL,
    authorization_code_value text DEFAULT NULL,
    authorization_code_issued_at timestamptz DEFAULT NULL,
    authorization_code_expires_at timestamptz DEFAULT NULL,
    authorization_code_metadata text DEFAULT NULL,
    access_token_value text DEFAULT NULL,
    access_token_issued_at timestamptz DEFAULT NULL,
    access_token_expires_at timestamptz DEFAULT NULL,
    access_token_metadata text DEFAULT NULL,
    access_token_type varchar(100) DEFAULT NULL,
    access_token_scopes varchar(1000) DEFAULT NULL,
    oidc_id_token_value text DEFAULT NULL,
    oidc_id_token_issued_at timestamptz DEFAULT NULL,
    oidc_id_token_expires_at timestamptz DEFAULT NULL,
    oidc_id_token_metadata text DEFAULT NULL,
    refresh_token_value text DEFAULT NULL,
    refresh_token_issued_at timestamptz DEFAULT NULL,
    refresh_token_expires_at timestamptz DEFAULT NULL,
    refresh_token_metadata text DEFAULT NULL,
    user_code_value text DEFAULT NULL,
    user_code_issued_at timestamptz DEFAULT NULL,
    user_code_expires_at timestamptz DEFAULT NULL,
    user_code_metadata text DEFAULT NULL,
    device_code_value text DEFAULT NULL,
    device_code_issued_at timestamptz DEFAULT NULL,
    device_code_expires_at timestamptz DEFAULT NULL,
    device_code_metadata text DEFAULT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE oauth2_authorization_consent (
    registered_client_id varchar(100) NOT NULL,
    principal_name varchar(200) NOT NULL,
    authorities varchar(1000) NOT NULL,
    PRIMARY KEY (registered_client_id, principal_name)
);

CREATE TABLE SPRING_SESSION (
	PRIMARY_ID CHAR(36) NOT NULL,
	SESSION_ID CHAR(36) NOT NULL,
	CREATION_TIME BIGINT NOT NULL,
	LAST_ACCESS_TIME BIGINT NOT NULL,
	MAX_INACTIVE_INTERVAL INT NOT NULL,
	EXPIRY_TIME BIGINT NOT NULL,
	PRINCIPAL_NAME VARCHAR(100),
	CONSTRAINT SPRING_SESSION_PK PRIMARY KEY (PRIMARY_ID)
);

CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION (SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION (PRINCIPAL_NAME);

CREATE TABLE SPRING_SESSION_ATTRIBUTES (
	SESSION_PRIMARY_ID CHAR(36) NOT NULL,
	ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
	ATTRIBUTE_BYTES BYTEA NOT NULL,
	CONSTRAINT SPRING_SESSION_ATTRIBUTES_PK PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
	CONSTRAINT SPRING_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID) REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE
);

CREATE TABLE user_login (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_info_id BIGINT NOT NULL,
    login_client VARCHAR(512) NOT NULL,
    client_id VARCHAR(128) NOT NULL,
    authorization_id VARCHAR(100) NOT NULL UNIQUE REFERENCES oauth2_authorization(id) ON DELETE CASCADE,
    authentication_session_id VARCHAR(36),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by VARCHAR(128) NOT NULL,
    updated_by VARCHAR(128) NOT NULL,
    CONSTRAINT fk_user_login_user_info
        FOREIGN KEY (user_info_id)
        REFERENCES user_info (id)
        ON DELETE CASCADE
);

CREATE INDEX idx_user_login_user_info_id ON user_login (user_info_id);
CREATE INDEX idx_user_login_expires_at ON user_login (expires_at);

COMMENT ON TABLE user_info IS '系统账户信息';
COMMENT ON COLUMN user_info.user_pass IS 'BCrypt 密码摘要';
COMMENT ON COLUMN user_info.user_permissions IS 'Sorted grants: uppercase subsystem abbreviation (MGR) or namespaced API permission (MGR:user:list)';
COMMENT ON TABLE user_login IS '账户登录客户端与授权会话';
COMMENT ON COLUMN user_login.client_id IS 'Login client identity, independent of authorized subsystems';

CREATE FUNCTION cleanup_inactive_user_login_sessions()
RETURNS integer
LANGUAGE plpgsql
SET search_path FROM CURRENT
AS $$
DECLARE
    deleted_count integer;
BEGIN
    DELETE FROM user_login
     WHERE updated_at < CURRENT_TIMESTAMP - INTERVAL '1 day';

    GET DIAGNOSTICS deleted_count = ROW_COUNT;
    RETURN deleted_count;
END;
$$;

COMMENT ON FUNCTION cleanup_inactive_user_login_sessions()
    IS 'Delete user_login rows whose updated_at has not changed for more than one day.';

COMMENT ON COLUMN user_info.enabled IS '账号是否允许登录和刷新令牌';

CREATE TABLE permission_change_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_user_id BIGINT NOT NULL,
    target_user_id BIGINT NOT NULL,
    before_permissions TEXT NOT NULL,
    after_permissions TEXT NOT NULL,
    before_enabled BOOLEAN NOT NULL,
    after_enabled BOOLEAN NOT NULL,
    trace_id VARCHAR(128) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_permission_change_audit_target_occurred
    ON permission_change_audit (target_user_id, occurred_at DESC);

COMMENT ON TABLE permission_change_audit IS 'Manager 账号授权与启停状态变更审计';
COMMENT ON COLUMN permission_change_audit.operator_user_id IS '执行变更的 Manager 用户 ID';
COMMENT ON COLUMN permission_change_audit.target_user_id IS '被变更的用户 ID';
COMMENT ON COLUMN permission_change_audit.before_permissions IS '变更前按稳定顺序编码的权限集合';
COMMENT ON COLUMN permission_change_audit.after_permissions IS '变更后按稳定顺序编码的权限集合';
COMMENT ON COLUMN permission_change_audit.trace_id IS '触发变更请求的链路追踪 ID';


CREATE INDEX idx_oauth2_authorization_principal ON oauth2_authorization(principal_name);

CREATE FUNCTION revoke_login_authorization() RETURNS trigger LANGUAGE plpgsql
SET search_path FROM CURRENT AS $$
BEGIN
    DELETE FROM oauth2_authorization WHERE id=OLD.authorization_id;
    DELETE FROM spring_session WHERE session_id=OLD.authentication_session_id;
    RETURN OLD;
END;
$$;
CREATE TRIGGER revoke_login_authorization AFTER DELETE ON user_login
FOR EACH ROW EXECUTE FUNCTION revoke_login_authorization();

CREATE FUNCTION revoke_changed_account_authorizations() RETURNS trigger LANGUAGE plpgsql
SET search_path FROM CURRENT AS $$
BEGIN
    IF TG_OP='DELETE' OR OLD.user_name IS DISTINCT FROM NEW.user_name
        OR OLD.user_pass IS DISTINCT FROM NEW.user_pass
        OR OLD.enabled IS DISTINCT FROM NEW.enabled
        OR OLD.user_permissions IS DISTINCT FROM NEW.user_permissions THEN
        DELETE FROM oauth2_authorization WHERE principal_name=OLD.id::text;
        DELETE FROM spring_session WHERE principal_name=OLD.id::text;
    END IF;
    RETURN OLD;
END;
$$;
CREATE TRIGGER revoke_changed_account_authorizations AFTER UPDATE OR DELETE ON user_info
FOR EACH ROW EXECUTE FUNCTION revoke_changed_account_authorizations();

